"""Jazyk rozhraní podle jazyka Windows. Neznámý jazyk spadne na angličtinu."""

from __future__ import annotations

import ctypes
import locale


SUPPORTED = ("cs", "sk", "en", "de", "pl", "fr", "es")

# Primární LANGID z GetUserDefaultUILanguage.
_PRIMARY = {
    0x05: "cs",
    0x1B: "sk",
    0x09: "en",
    0x07: "de",
    0x15: "pl",
    0x0C: "fr",
    0x0A: "es",
}


def detect_language() -> str:
    try:
        lang_id = int(ctypes.windll.kernel32.GetUserDefaultUILanguage())
        primary = lang_id & 0x3FF
        if primary in _PRIMARY:
            return _PRIMARY[primary]
        if primary:
            return "en"
    except Exception:
        pass
    try:
        code = (locale.getdefaultlocale()[0] or "").replace("-", "_").split("_")[0].lower()
    except Exception:
        code = ""
    if code in SUPPORTED:
        return code
    return "en"


LANG = detect_language()


def language() -> str:
    return LANG


def comma_decimal() -> bool:
    return LANG != "en"


def tr(message: str, **kwargs) -> str:
    text = message
    if LANG != "cs" and message:
        bundle = CATALOG.get(LANG) or CATALOG["en"]
        translated = bundle.get(message)
        if translated is None and LANG != "en":
            translated = CATALOG["en"].get(message)
        if translated is not None:
            text = translated
    if kwargs:
        return text.format(**kwargs)
    return text


